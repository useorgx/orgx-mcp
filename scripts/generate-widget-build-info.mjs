import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { computeWidgetBuildVersion } from './lib/widgetBuildHash.mjs';

const root = process.cwd();
const widgetRoot = resolve(root, 'public/widgets');
const outputFile = resolve(root, 'src/generated/widgetBuildInfo.ts');

const widgetBuildVersion = computeWidgetBuildVersion(root);
const nextSource = `// Auto-generated by scripts/generate-widget-build-info.mjs\nexport const WIDGET_BUILD_VERSION = '${widgetBuildVersion}' as const;\n`;

mkdirSync(resolve(root, 'src/generated'), { recursive: true });

let previousSource = null;
try {
  previousSource = readFileSync(outputFile, 'utf8');
} catch {
  previousSource = null;
}

if (previousSource !== nextSource) {
  writeFileSync(outputFile, nextSource, 'utf8');
}
