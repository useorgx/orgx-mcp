import { createHash } from 'node:crypto';
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { join, relative, resolve } from 'node:path';

const root = process.cwd();
const widgetRoot = resolve(root, 'public/widgets');
const outputFile = resolve(root, 'src/generated/widgetBuildInfo.ts');

function collectFiles(dir) {
  const entries = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.name !== '.DS_Store')
    .sort((a, b) => a.name.localeCompare(b.name));

  const files = [];
  for (const entry of entries) {
    const absolutePath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectFiles(absolutePath));
      continue;
    }
    if (entry.isFile()) {
      files.push(absolutePath);
    }
  }
  return files;
}

if (!statSync(widgetRoot).isDirectory()) {
  throw new Error(`Widget directory not found: ${widgetRoot}`);
}

const hash = createHash('sha256');
for (const filePath of collectFiles(widgetRoot)) {
  hash.update(relative(root, filePath));
  hash.update('\0');
  hash.update(readFileSync(filePath));
  hash.update('\0');
}

const widgetBuildVersion = hash.digest('hex').slice(0, 12);
const nextSource = `// Auto-generated by scripts/generate-widget-build-info.mjs\nexport const WIDGET_BUILD_VERSION = '${widgetBuildVersion}' as const;\n`;

mkdirSync(resolve(root, 'src/generated'), { recursive: true });

let previousSource = null;
try {
  previousSource = readFileSync(outputFile, 'utf8');
} catch {
  previousSource = null;
}

if (previousSource !== nextSource) {
  writeFileSync(outputFile, nextSource, 'utf8');
}
